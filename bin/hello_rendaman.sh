#!/usr/bin/env bash
# ─── 1. バナー文字列を用意 ────────────────────────────────────
read -r -d '' banner_lines <<'EOF'
,--.  ,--.         ,--. ,--.                                       ,--.                                       
|  '--'  |  ,---.  |  | |  |  ,---.    ,--.--.  ,---.  ,--,--,   ,-|  |  ,--,--. ,--,--,--.  ,--,--. ,--,--,  
|  .--.  | | .-. : |  | |  | | .-. |   |  .--' | .-. : |      \ ' .-. | ' ,-.  | |        | ' ,-.  | |      \ 
|  |  |  | \   --. |  | |  | ' '-' '   |  |    \   --. |  ||  | \ `-' | \ '-'  | |  |  |  | \ '-'  | |  ||  | 
`--'  `--'  `----' `--' `--'  `---'    `--'     `----' `--''--'  `---'   `--`--' `--`--`--'  `--`--' `--''--' 
EOF

# ─── 2. 色設定（ANSI 8-color） ─────────────────────────────────
colors=(31 33 32 36 34 35)   # 赤 黄 緑 シアン 青 マゼンタ

# ─── 3. 行ごとに色を変えて表示 ───────────────────────────────
i=0
while IFS= read -r line; do
  printf '\e[1;%sm%s\e[0m\n' "${colors[i]}" "$line"
  (( i = (i + 1) % ${#colors[@]} ))
done <<<"$banner_lines"
